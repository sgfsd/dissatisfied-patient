export const CALIBRATION_BLOCK = `
КАЛИБРОВКА (эталонные примеры для универсальных критериев 1–4;
пятый критерий оценивай строго по его формулировке выше):

ЭТАЛОН 1 (сильный ответ врача). Пациентка: «Я записана на 10:20, а меня позвали в 13:40. Я отпросилась с работы, у меня там отчёт горит, а я тут два часа сижу, и никто даже не извинился».
Врач: «Слышу, как это выбило вас из колеи — вы отпросились с работы, а тут два часа ожидания без объяснений. Это действительно неприятно и несправедливо. Давайте я сейчас посмотрю, что с вашей картой, и уточню, почему вышла задержка; затем мы быстро всё закроем. Вы на работе по какому времени успеваете?»
Баллы: Распознавание эмоции — 3 (назвал чувство и привязал к конкретике: работа, два часа, без объяснений). Уважение/без обороны — 3. Прояснение — 2 (уточнил про время, карту, задержку). Конкретный шаг — 2 (посмотреть карту, уточнить причину, закрыть вопрос). Не дал ложных обещаний, не обвинил регистратуру — уважительно.

ЭТАЛОН 2 (слабый, оборонительный ответ). Та же пациентка.
Врач: «Понимаю. Но вы же видите, какой у нас сегодня поток, мы не виноваты. Всех принимаем по очереди. Присядьте, подождите ещё немного, вас позовут».
Баллы: Распознавание эмоции — 1 (формальное «понимаю» без связи с ситуацией). Уважение/без обороны — 1 (оправдания «мы не виноваты» + указание «присядьте»). Прояснение — 0. Конкретный шаг — 0 (нет действий, только «ждите»).

ЭТАЛОН 3 (середина). Врач: «Простите за ожидание — два часа это действительно долго, особенно когда вы отпросились с работы. Сейчас посмотрю, в чём задержка по вашей карте, и постараюсь ускорить.»
Баллы: Распознавание эмоции — 2 (признал тяжесть, но эмоцию назвал обобщённо). Уважение/без обороны — 2 (есть «простите», но без самобичевания; тон рабочий). Прояснение — 1. Конкретный шаг — 2.`;

/** Тон текстов объяснений: пользователь выбрал «максимально прямо». */
export const TONE_RULE = `
ТОН ОБЪЯСНЕНИЙ: формулируй прямо и по делу, без смягчений и «подслащивания».
Если критерий не выполнен — так и напиши, покажи, чего конкретно не хватило и
что именно сказать вместо этого. Не растягивай: 1–2 предложения на критерий.
Не хвали за то, чего не было. Точность важнее мягкости.`;

import { domainByKey, domainByRubricId } from '../domains';

export function calibrationForScenario(domainKey?: string, rubricId?: string): string {
  const domain = domainByRubricId(rubricId) ?? domainByKey(domainKey);
  if (!domain) return CALIBRATION_BLOCK;
  return [
    `КАЛИБРОВКА ДОМЕНА «${domain.card.title}» (${domain.card.framework}):`,
    ...domain.calibration.map((item, i) => [
      `ЭТАЛОН ${i + 1}: ${item.title}`,
      `Собеседник: «${item.patient}»`,
      `Ответ специалиста: «${item.clinician}»`,
      `Оценка: ${item.assessment}`,
    ].join('\n')),
  ].join('\n\n');
}
