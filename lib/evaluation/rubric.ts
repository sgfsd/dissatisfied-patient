/* Категорийный 5-й критерий: зависит от повода жалобы. */

function categoryExtra(title: string): CriterionDef {
  const t = title.toLowerCase();
  if (/(страх|тревог|диагноз|риск|осложнен|операци|объясн|результат|повторн)/.test(t)) {
    return {
      id: 'veracity',
      name: 'Честность без ложных обещаний',
      framework: 'Beauchamp & Childress (автономия, правдивость)',
      scale: 2,
      verify:
        'Врач не давал ложных гарантий («всё точно будет хорошо», «ничего страшного»), не скрывал неопределённость и риски, объяснял честно и понятно. ' +
        '2: честно о неопределённости/рисках, простым языком; 1: частично честен, но с «сглаживанием»; 0: ложные гарантии, сокрытие рисков, запугивание.',
    };
  }
  if (/(стоимост|платн|деньг|документ|направлен|страхов|смет|договор|счет)/.test(t)) {
    return {
      id: 'transparency',
      name: 'Прозрачность и пути решения',
      framework: 'Beauchamp & Childress (справедливость)',
      scale: 2,
      verify:
        'По деньгам/документам врач говорит ясно: что к чему относится, почему так, и предлагает реальные варианты, не отфутболивая. ' +
        '2: ясное объяснение + конкретные варианты; 1: объяснение есть, вариантов нет; 0: отфутболивание, «это не ко мне», неясность осталась.',
    };
  }
  if (/(очеред|запись|ожидан|организац|инфраструктур|перенос)/.test(t)) {
    return {
      id: 'respect-time',
      name: 'Признание неудобства',
      framework: 'NURSE (Respect) + справедливость',
      scale: 2,
      verify:
        'Врач признал факт неудобства/ожидания и его последствия для пациента, не отшутился и не переложил вину на «систему» в стиле «я тут ни при чём». ' +
        '2: признал и предложил, как сгладить; 1: признал формально; 0: отшутился, обвинил пациента или «систему» без эмпатии.',
    };
  }
  if (/(родственник|близк|ребен|родител|мать|отец|мама|папа)/.test(t)) {
    return {
      id: 'family',
      name: 'Вовлечение близкого/родителя',
      framework: 'Calgary–Cambridge Guide + автономия семьи',
      scale: 2,
      verify:
        'Врач обращается к обеспокоенному близкому/родителю как к полноправному участнику, отвечает на его тревогу и вовлекает в план. ' +
        '2: тревога близкого признана, он вовлечён в решение; 1: частично; 0: близкого/родителя игнорируют или обесценивают его роль.',
    };
  }
  return {
    id: 'empathy-support',
    name: 'Эмоциональная поддержка',
    framework: 'NURSE (Support)',
    scale: 2,
    verify:
      'Врач выразил поддержку и готовность быть рядом в решении проблемы (не пустые слова, а конкретная опора). ' +
      '2: поддержка конкретна и адресна; 1: дежурная; 0: поддержки нет, пациент остался один на один с проблемой.',
  };
}

/** Рубрика для сцены: 4 универсальных + 1 категорийный критерий. */
export function rubricForCategory(categoryTitle: string): CriterionDef[] {
  return [...UNIVERSAL, categoryExtra(categoryTitle)];
}

/** Новая точка входа; без параметров сохраняет прежнюю конфликтную рубрику. */
export function rubricForScenario(categoryTitle: string, domainKey?: string, rubricId?: string): CriterionDef[] {
  const domain = domainByRubricId(rubricId) ?? (domainKey ? domainByKey(domainKey) : undefined);
  return domain ? domain.rubric.map((item) => ({ ...item })) : rubricForCategory(categoryTitle);
}

export const RUBRIC_MAX_SCORE = UNIVERSAL.reduce((s, c) => s + c.scale, 0) + 2; // = 12

/** Текстовое представление рубрики для промта оценщика. */
export function rubricToPrompt(rubric: CriterionDef[]): string {
  return rubric
    .map(
      (c, i) =>
        `${i + 1}. ${c.name} (шкала 0–${c.scale}, основа: ${c.framework})\n   Проверка: ${c.verify}`
    )
    .join('\n\n');
}

export function rubricNames(rubric: CriterionDef[]): Set<string> {
  return new Set(rubric.map((c) => c.name));
}
