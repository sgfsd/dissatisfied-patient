export function complaintCategoriesFor(domain: DomainSlug): ComplaintCategory[] {
  return COMPLAINT_CATEGORIES[domain];
}

export function domainBySlug(slug: string): DomainDef | undefined {
  return DOMAINS.find((d) => d.slug === slug);
}

export const DOMAIN_SLUGS = DOMAINS.map((d) => d.slug);
