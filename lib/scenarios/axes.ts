/** Поводы домена в формате сценарных осей. */
export function complaintCategoriesFor(domainKey: DomainSlug): ComplaintCategory[] {
  return (domainByKey(domainKey)?.cases ?? []).map((item) => ({
    title: item.title,
    brief: item.brief,
    seeds: [...item.seeds],
  }));
}

/** Персонажи, уместные для кейса: приоритет у пула кейса, иначе все. */
export function personaPoolFor(item?: DomainCaseDef): string[] {
  const pool = item?.personaPool?.filter((key) => PERSONAS.some((persona) => persona.key === key));
  return pool?.length ? pool : PERSONAS.map((persona) => persona.key);
}
