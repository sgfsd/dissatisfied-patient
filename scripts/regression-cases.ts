/* ============================================================
   Регрессионный набор оценщика. 18 эталонных диалогов «врач ×
   пациент» с ожидаемыми диапазонами баллов по каждому критерию.
   Каждый кейс — это сценарий, который живой прогон мог бы дать
   (та же схема EvaluateParams), поэтому оценщик проверяется на
   настоящих входных данных, а не на юнитах.

   Диапазоны намеренно не точечные: оценка LLM не детерминирована
   на 100% даже при temperature=0, но сдвиг за пределы диапазона —
   это регресс промта/рубрики.

   ВАЖНО: диапазоны привязаны к модели-оценщику по умолчанию.
   2026-09-08 — перекалибровка под gpt-4o-mini (детерминированная,
   дефолтная модель; строже gpt-4o к обесцениванию и «пустым» шагам).
   Жёсткие якоря сохранены: сильные кейсы 12/12, грубость/обвинение ~0,
   ложные гарантии не дают «Честности» 2, шаблон и односложность не
   дают «Распознавания». При смене модели оценщика прогоняйте регресс
   и перекалибровывайте осознанно.
   ============================================================ */

import type { HiddenMotive, PatientEmotion } from '../lib/types';

export interface CaseExpectCriterion {
  name: string;
  min: number;
  max: number;
}

export interface RegressionCase {
  key: string;                      // короткое имя для отчёта и фильтра --case
  title: string;                    // человекочитаемое описание кейса
  domain: string;                   // полное имя домена (контекст для оценщика)
  category: string;                 // полный заголовок категории → 5-й критерий
  personaKey: string;
  moodLabel?: string;
  complaint: string;                // complaintSeed
  motive: HiddenMotive;
  actingNotes?: string;
  opener: { text: string; emotion: PatientEmotion };
  /** Ответы врача; после каждого — необязательная реплика пациента. */
  dialogue: { doctor: string; patient?: { text: string; emotion: PatientEmotion } }[];
  criteria: CaseExpectCriterion[];  // ожидания по КАЖДОМУ критерию рубрики (по name)
  total: [number, number];          // ожидаемый диапазон суммы баллов
  expectSafety?: boolean;           // true — safety_flag обязан быть непустым
  expectInjectionFlag?: boolean;    // true — в flags обязан быть prompt_injection
}

